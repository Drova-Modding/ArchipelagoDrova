using UnityEngine;

namespace ArchipelagoDrova.Data
{
    /// <summary>
    /// One piece of library floor riddle clue art: the image a "Geschichte der Runenmagie" book
    /// displays to name a floor rune of the circle room riddle. Pixels are RRGGBBAA hex in
    /// Unity's bottom-up SetPixels32 row order.
    /// </summary>
    public readonly struct FloorClueArt
    {
        public readonly int W;
        public readonly int H;
        public readonly string Hex;

        public FloorClueArt(int w, int h, string hex)
        {
            W = w;
            H = h;
            Hex = hex;
        }
    }

    /// <summary>
    /// Floor rune key -> clue art. The contents live in FloorClueTable.g.cs, generated by
    /// tools/extract_locations/gen_floor_clue_table.py from the same extraction as the apworld's
    /// floor_runes.json so the two can never drift.
    /// </summary>
    public static partial class FloorClueTable
    {
        /// <summary>
        /// The clue images of books I -> II -> III, which is also the vanilla stairs sequence of
        /// the riddle. Slot n of a shuffled sequence replaces the art of book n + 1.
        /// </summary>
        public static readonly string[] VanillaSequence = ["Energy", "Root", "Fire"];

        /// <summary>
        /// Decode one clue into RGBA32 pixels for SetPixels32. Returns null for unknown names.
        /// </summary>
        public static Color32[] DecodePixels(string runeName, out int width, out int height)
        {
            width = 0;
            height = 0;
            if (!Generated.TryGetValue(runeName, out FloorClueArt art)
                || art.Hex.Length != art.W * art.H * 8)
            {
                return null;
            }

            width = art.W;
            height = art.H;
            var pixels = new Color32[art.W * art.H];
            for (int i = 0; i < pixels.Length; i++)
            {
                int o = i * 8;
                pixels[i] = new Color32(
                    ParseByte(art.Hex, o), ParseByte(art.Hex, o + 2),
                    ParseByte(art.Hex, o + 4), ParseByte(art.Hex, o + 6));
            }
            return pixels;
        }

        private static byte ParseByte(string hex, int offset)
        {
            return (byte)(Nibble(hex[offset]) << 4 | Nibble(hex[offset + 1]));
        }

        private static int Nibble(char c)
        {
            if (c >= '0' && c <= '9')
            {
                return c - '0';
            }
            return char.ToLowerInvariant(c) - 'a' + 10;
        }
    }
}
