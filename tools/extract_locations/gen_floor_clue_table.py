"""Freeze the library floor riddle clue art for the floor rune shuffle.

The library books "Geschichte der Runenmagie I-III" each display one clue sprite
(GUI_Notes_Library_RuneClue_0/1/2 = Root/Fire/Energy) naming a floor rune of the circle
room riddle; book IV describes the Sound and Summon runes without a picture. The game
ships no clue art for those two, so they were pixeled for the randomizer by hand in the
same note-paper style (assets/rune_1.png = Sound, assets/rune_2.png = Summon).

Outputs:
  - apworld/drova/data/floor_runes.json       the 5 rune keys + the vanilla book order
  - ArchipelagoDrova/Data/FloorClueTable.g.cs rune key -> clue art (w, h, RRGGBBAA hex,
                                              Unity bottom-up row order)

The client rebuilds clue sprites from these pixels, exactly like RuneTable does for the
drawing riddles, so a book can hint any rune without the partner art's bundle loaded.
"""
import UnityPy, glob, os, json
from PIL import Image

BD = r"C:\Program Files (x86)\Steam\steamapps\common\Drova - Forsaken Kin\Drova_Data\StreamingAssets\aa\StandaloneWindows64"
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT_JSON = os.path.join(REPO, "apworld", "drova", "data", "floor_runes.json")
OUT_CS = os.path.join(REPO, "ArchipelagoDrova", "Data", "FloorClueTable.g.cs")

# Sprite name in the letter prefabs -> rune key. The letter swap matches by sprite name at
# runtime, so these names are load-bearing on the client too.
VANILLA_SPRITES = {
    "GUI_Notes_Library_RuneClue_0": "Root",
    "GUI_Notes_Library_RuneClue_1": "Fire",
    "GUI_Notes_Library_RuneClue_2": "Energy",
}
# Hand-pixeled clue art for the two runes the game never illustrates.
PIXELED = {
    "Sound": os.path.join(REPO, "assets", "rune_1.png"),
    "Summon": os.path.join(REPO, "assets", "rune_2.png"),
}
# Book I -> II -> III images, i.e. the vanilla solution sequence of the floor riddle.
VANILLA_ORDER = ["Energy", "Root", "Fire"]


def encode(img):
    """PIL image -> (w, h, hex) with rows flipped to Unity's bottom-up SetPixels32 order."""
    img = img.convert("RGBA")
    flipped = img.transpose(Image.FLIP_TOP_BOTTOM)
    px = list(flipped.getdata())
    return img.width, img.height, "".join(f"{r:02x}{g:02x}{b:02x}{a:02x}" for r, g, b, a in px)


art = {}  # rune key -> (w, h, hex)
for f in sorted(glob.glob(os.path.join(BD, "*.bundle"))):
    try:
        env = UnityPy.load(f)
    except Exception:
        continue
    for o in env.objects:
        if o.type.name != "Sprite":
            continue
        try:
            d = o.read()
        except Exception:
            continue
        rune = VANILLA_SPRITES.get(d.m_Name)
        if rune is None or rune in art:
            continue
        art[rune] = encode(d.image)
    if len(art) == len(VANILLA_SPRITES):
        break
assert len(art) == len(VANILLA_SPRITES), f"clue sprites not found: {set(VANILLA_SPRITES.values()) - set(art)}"

for rune, path in PIXELED.items():
    art[rune] = encode(Image.open(path))

for rune, (w, h, _) in sorted(art.items()):
    print(f"{rune}: {w}x{h}")

json.dump(
    {"runes": sorted(art), "vanilla_order": VANILLA_ORDER},
    open(OUT_JSON, "w", encoding="utf-8"), ensure_ascii=True, indent=1)
print(f"pool -> {OUT_JSON}")

lines = [
    "// Generated by tools/extract_locations/gen_floor_clue_table.py. Do not edit by hand.",
    "using System.Collections.Generic;",
    "",
    "namespace ArchipelagoDrova.Data",
    "{",
    "    public static partial class FloorClueTable",
    "    {",
    "        /// <summary>Floor rune key -> clue art pixels (RRGGBBAA hex, Unity bottom-up",
    "        /// row order). Root/Fire/Energy are copied verbatim from the game's",
    "        /// GUI_Notes_Library_RuneClue_0/1/2 sprites; Sound and Summon were hand-pixeled",
    "        /// for the randomizer (the game ships no clue art for them).</summary>",
    "        public static readonly Dictionary<string, FloorClueArt> Generated = new Dictionary<string, FloorClueArt>",
    "        {",
]
for rune in sorted(art):
    w, h, hexs = art[rune]
    lines.append(f'            {{ "{rune}", new FloorClueArt({w}, {h}, "{hexs}") }},')
lines += ["        };", "    }", "}", ""]
open(OUT_CS, "w", encoding="utf-8").write("\n".join(lines))
print(f"table: {len(art)} clues -> {OUT_CS}")
